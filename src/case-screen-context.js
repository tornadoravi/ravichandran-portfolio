export function explainCaseScreen(src) {
  const filename = src.split('/').pop();
  const explanation = explanations[filename];
  const name = screenNames[filename];
  if (!explanation || !name) throw new Error(`Missing case-study screen context: ${filename}`);
  return `${name}: ${explanation}`;
}
